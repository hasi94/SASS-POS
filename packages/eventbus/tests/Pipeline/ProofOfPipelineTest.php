<?php

declare(strict_types=1);

namespace Flexipos\Eventbus\Tests\Pipeline;

/*
|--------------------------------------------------------------------------
| T-018 step 9 - the proof-of-pipeline example (Ruling 1, AC-34)
|--------------------------------------------------------------------------
|
| This is a fixture proving the mechanism end to end, not new business
| scope (D-10, AC-35): `fixture.pinged` is this task's one example event,
| its consumer lives in this package's own test tree rather than in a
| module (modules/demo is regenerated byte-for-byte by `module:make demo`;
| a consumer there would break ModuleMakeDemoRegenerationTest - Ruling 1),
| and it imports nothing under Flexipos\Eventbus\ (QaEventbusSourceRulesTest
| asserts that structurally).
|
| One test, end to end, on the stand-in: write through the one outbox
| writer inside the caller's own transaction, relay it, deliver it to a
| consumer group member, handle it idempotently, acknowledge it, and prove
| a simulated redelivery is a safe no-op.
*/

use Flexipos\Access\Tests\Support\AccessTenantFixture;
use Flexipos\Contracts\Events\EventActor;
use Flexipos\Contracts\Events\EventEnvelope;
use Flexipos\Contracts\Events\NewEvent;
use Flexipos\Contracts\Events\Outbox;
use Flexipos\Eventbus\Bus\InMemoryEventBus;
use Flexipos\Eventbus\Tests\Support\FixtureEventConsumerProvider;
use Flexipos\Eventbus\Tests\Support\PingedConsumer;
use Illuminate\Support\Facades\Artisan;
use Illuminate\Support\Facades\DB;
use Tests\TestCase;

require_once __DIR__.'/../Support/eventbus-fixture.php';

uses(TestCase::class);

beforeEach(function () {
    AccessTenantFixture::boot();
    eventbusEnterTenant('tenant-a');
    eventbusCreatePingsTable();
    eventbusCreateMarkerTable();
    DB::connection(AccessTenantFixture::connectionName())->table('eventbus_marker')->insert(['value' => 'before']);
    tenancy()->leave();

    PingedConsumer::reset();
});

afterEach(function () {
    if (tenancy()->current()->hasTenant()) {
        tenancy()->leave();
    }

    AccessTenantFixture::forget();
});

it('AC-34: writes, relays, delivers, handles idempotently and acknowledges fixture.pinged end to end', function () {
    FixtureEventConsumerProvider::declaring(app(), [PingedConsumer::class]);

    eventbusEnterTenant('tenant-a');

    $connection = DB::connection(AccessTenantFixture::connectionName());
    $eventId = $connection->transaction(function () use ($connection): string {
        $connection->table('eventbus_marker')->update(['value' => 'after']);

        return app(Outbox::class)->record(new NewEvent(
            PingedConsumer::EVENT_TYPE,
            'fixture',
            '01ARZ3NDEKTSV4RRFFQ69G5FAV',
        ));
    });

    $outboxRowBefore = $connection->table('outbox_events')->where('id', $eventId)->first();
    expect($outboxRowBefore->status)->toBe('pending');
    expect($connection->table('eventbus_marker')->first()->value)->toBe('after');

    tenancy()->leave();

    $relayExit = Artisan::call('eventbus:relay', ['--once' => true, '--tenant' => ['tenant-a']]);
    expect($relayExit)->toBe(0);

    eventbusEnterTenant('tenant-a');
    $outboxRowAfter = $connection->table('outbox_events')->where('id', $eventId)->first();
    expect($outboxRowAfter->status)->toBe('published');
    tenancy()->leave();

    $consumeExit = Artisan::call('eventbus:consume', ['--group' => [PingedConsumer::GROUP], '--once' => true]);
    expect($consumeExit)->toBe(0);

    eventbusEnterTenant('tenant-a');

    $pings = $connection->table('fixture_pings')->get();
    expect($pings)->toHaveCount(1);
    expect($pings[0]->event_id)->toBe($eventId);

    $bus = app(InMemoryEventBus::class);
    $stream = (string) config('eventbus.stream');
    expect($bus->pending($stream, PingedConsumer::GROUP, 10))->toBe([]);

    // A simulated redelivery of the identical envelope - the consumer
    // called directly a second time, exactly as a crash-then-redeliver
    // would present it - is a safe no-op: it checks before acting, by the
    // event's own identifier (AC-23), so fixture_pings still holds one row.
    $redelivered = new EventEnvelope(
        $eventId,
        'tenant-a',
        PingedConsumer::EVENT_TYPE,
        1,
        'fixture',
        '01ARZ3NDEKTSV4RRFFQ69G5FAV',
        null,
        null,
        $outboxRowBefore->occurred_at,
        null,
        null,
        EventActor::system(),
    );

    (new PingedConsumer)->handle($redelivered);

    expect($connection->table('fixture_pings')->count())->toBe(1);
});
